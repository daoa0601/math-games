// ========================================
// Shape Architect - Puzzle Solver
// Backtracking solver with early termination
// ========================================

import type { LevelConfig, Piece, Position3D, Rotation3D, CellState } from './types';
import {
    initializeGrid,
    rotatePieceLayout3D,
    canPlacePiece,
    placePiece,
    checkSolved,
} from './engine';

// ========================================
// Types
// ========================================

export interface SolutionStep {
    pieceId: string;
    position: Position3D;
    rotation: Rotation3D;
}

export interface SolverResult {
    solvable: boolean;
    solution?: SolutionStep[];
    searchedStates: number;
    timeMs: number;
    timedOut: boolean;  // true if search timed out before completion
}

// ========================================
// Rotation Generation
// ========================================

/**
 * Generate all 4 unique 2D rotations (Z-axis only)
 * Used for 2D levels where pieces only rotate on the floor plane
 */
export function generate2DRotations(): Rotation3D[] {
    return [
        { x: 0, y: 0, z: 0 },
        { x: 0, y: 0, z: 90 },
        { x: 0, y: 0, z: 180 },
        { x: 0, y: 0, z: 270 },
    ];
}

/**
 * Generate all 24 unique 3D rotations (all orientations)
 * A cube has 24 possible orientations:
 * - 6 faces can point up (face direction)
 * - Each face has 4 rotations around that axis
 *
 * We explicitly enumerate all 24 unique rotations rather than deriving them,
 * as this is more reliable and efficient.
 */
export function generate3DRotations(): Rotation3D[] {
    // The 24 unique orientations of a cube can be generated by:
    // 1. 6 ways to choose which face points up (positive/negative X, Y, or Z)
    // 2. 4 rotations around that axis for each face direction
    //
    // We enumerate them explicitly for clarity and correctness:
    return [
        // +Y face up (identity): 4 rotations around Y
        { x: 0, y: 0, z: 0 },
        { x: 0, y: 90, z: 0 },
        { x: 0, y: 180, z: 0 },
        { x: 0, y: 270, z: 0 },

        // -Y face up (flip 180 around X or Z): 4 rotations around Y
        { x: 180, y: 0, z: 0 },
        { x: 180, y: 90, z: 0 },
        { x: 180, y: 180, z: 0 },
        { x: 180, y: 270, z: 0 },

        // +X face up (rotate 90 around Z): 4 rotations around X
        { x: 0, y: 0, z: 90 },
        { x: 90, y: 0, z: 90 },
        { x: 180, y: 0, z: 90 },
        { x: 270, y: 0, z: 90 },

        // -X face up (rotate -90 around Z): 4 rotations around X
        { x: 0, y: 0, z: 270 },
        { x: 90, y: 0, z: 270 },
        { x: 180, y: 0, z: 270 },
        { x: 270, y: 0, z: 270 },

        // +Z face up (rotate -90 around X): 4 rotations around Z
        { x: 270, y: 0, z: 0 },
        { x: 270, y: 0, z: 90 },
        { x: 270, y: 0, z: 180 },
        { x: 270, y: 0, z: 270 },

        // -Z face up (rotate 90 around X): 4 rotations around Z
        { x: 90, y: 0, z: 0 },
        { x: 90, y: 0, z: 90 },
        { x: 90, y: 0, z: 180 },
        { x: 90, y: 0, z: 270 },
    ];
}

// Pre-compute rotations for performance
const ROTATIONS_2D = generate2DRotations();
const ROTATIONS_3D = generate3DRotations();

// ========================================
// Helper Functions
// ========================================

/**
 * Find the first unfilled target cell
 * Returns null if all targets are filled
 */
function findFirstUnfilledTarget(
    grid: CellState[][][],
    targetVoxels: Position3D[]
): Position3D | null {
    for (const pos of targetVoxels) {
        if (grid[pos.x][pos.y][pos.z] === 1) {
            return pos;
        }
    }
    return null;
}

/**
 * Get unique rotated layouts for a piece, filtering out duplicates
 * Some pieces (like O-block) look the same after certain rotations
 */
function getUniqueRotations(piece: Piece, rotations: Rotation3D[]): Rotation3D[] {
    const seen = new Set<string>();
    const uniqueRotations: Rotation3D[] = [];

    for (const rotation of rotations) {
        const rotated = rotatePieceLayout3D(piece.layout, rotation);
        const sorted = [...rotated].sort((a, b) =>
            a.x !== b.x ? a.x - b.x : a.y !== b.y ? a.y - b.y : a.z - b.z
        );
        const key = sorted.map(p => `${p.x},${p.y},${p.z}`).join('|');

        if (!seen.has(key)) {
            seen.add(key);
            uniqueRotations.push(rotation);
        }
    }

    return uniqueRotations;
}

/**
 * Find all positions where a piece could be placed to cover a specific target cell
 */
function findCandidatePositions(
    piece: Piece,
    rotation: Rotation3D,
    targetCell: Position3D,
    // eslint-disable-next-line @typescript-eslint/no-unused-vars
    _gridSize: [number, number, number]
): Position3D[] {
    const rotatedLayout = rotatePieceLayout3D(piece.layout, rotation);
    const candidates: Position3D[] = [];

    // For each cell in the rotated piece layout, calculate where the piece
    // would need to be positioned for that cell to cover the target
    for (const localPos of rotatedLayout) {
        const piecePosition: Position3D = {
            x: targetCell.x - localPos.x,
            y: targetCell.y - localPos.y,
            z: targetCell.z - localPos.z,
        };

        // Quick bounds check on piece position
        if (piecePosition.x >= 0 && piecePosition.y >= 0 && piecePosition.z >= 0) {
            candidates.push(piecePosition);
        }
    }

    return candidates;
}

// ========================================
// Main Solver
// ========================================

/**
 * Solve a puzzle using backtracking with early termination
 *
 * Algorithm:
 * 1. Find first unfilled target cell
 * 2. For each remaining piece:
 *    - For each rotation (4 for 2D, 24 for 3D):
 *      - Find positions where piece could cover the unfilled target
 *      - If valid placement: place piece, recurse
 *      - If recursion succeeds: return solution
 *      - Otherwise: backtrack (undo placement)
 * 3. If no pieces can fill the target: return unsolvable
 *
 * @param level The level configuration to solve
 * @param maxTimeMs Maximum time to search (default: 5000ms)
 * @returns Solver result with solvability and optional solution
 */
export function solvePuzzle(level: LevelConfig, maxTimeMs: number = 5000): SolverResult {
    const startTime = performance.now();
    let searchedStates = 0;

    // Handle edge cases
    if (level.targetVoxels.length === 0) {
        // Empty target is trivially solvable (no pieces needed)
        return {
            solvable: true,
            solution: [],
            searchedStates: 0,
            timeMs: performance.now() - startTime,
            timedOut: false,
        };
    }

    // Volume check: quick rejection if volumes don't match
    const targetVolume = level.targetVoxels.length;
    const pieceVolume = level.pieces.reduce((sum, p) => sum + p.layout.length, 0);

    if (pieceVolume !== targetVolume) {
        return {
            solvable: false,
            searchedStates: 0,
            timeMs: performance.now() - startTime,
            timedOut: false,
        };
    }

    // Select rotations based on level type
    const rotations = level.type === '3D' ? ROTATIONS_3D : ROTATIONS_2D;

    // Pre-compute unique rotations for each piece
    const pieceRotations = new Map<string, Rotation3D[]>();
    for (const piece of level.pieces) {
        pieceRotations.set(piece.id, getUniqueRotations(piece, rotations));
    }

    // Initialize grid with targets
    const initialGrid = initializeGrid(level);

    // Recursive backtracking solver
    function solve(
        grid: CellState[][][],
        remainingPieces: Piece[],
        solution: SolutionStep[]
    ): SolutionStep[] | null {
        // Check timeout
        if (performance.now() - startTime > maxTimeMs) {
            return null;
        }

        // Find first unfilled target
        const unfilled = findFirstUnfilledTarget(grid, level.targetVoxels);

        // If no unfilled targets, check if all targets are filled
        if (unfilled === null) {
            if (checkSolved(grid, level.targetVoxels)) {
                return solution;
            }
            return null;
        }

        // Try each remaining piece
        for (let i = 0; i < remainingPieces.length; i++) {
            const piece = remainingPieces[i];
            const uniqueRots = pieceRotations.get(piece.id)!;

            // Try each unique rotation
            for (const rotation of uniqueRots) {
                // Find candidate positions that would cover the unfilled target
                const candidates = findCandidatePositions(
                    piece,
                    rotation,
                    unfilled,
                    level.gridSize
                );

                // Try each candidate position
                for (const position of candidates) {
                    searchedStates++;

                    // Check if placement is valid
                    if (canPlacePiece(grid, piece, position, rotation, level.gridSize)) {
                        // Place the piece
                        const newGrid = placePiece(grid, piece, position, rotation);

                        // Remove piece from remaining
                        const newRemaining = [
                            ...remainingPieces.slice(0, i),
                            ...remainingPieces.slice(i + 1),
                        ];

                        // Add to solution
                        const newSolution: SolutionStep[] = [
                            ...solution,
                            { pieceId: piece.id, position, rotation },
                        ];

                        // Recurse
                        const result = solve(newGrid, newRemaining, newSolution);

                        if (result !== null) {
                            return result;
                        }

                        // Backtrack is implicit (we didn't modify grid or solution)
                    }

                    // Check timeout after each state
                    if (performance.now() - startTime > maxTimeMs) {
                        return null;
                    }
                }
            }
        }

        // No solution found from this state
        return null;
    }

    // Start solving
    const solution = solve(initialGrid, level.pieces, []);
    const timeMs = performance.now() - startTime;

    // Determine if we timed out or found a definitive answer
    const timedOut = timeMs >= maxTimeMs;

    return {
        solvable: solution !== null,
        solution: solution ?? undefined,
        searchedStates,
        timeMs,
        timedOut,
    };
}

/**
 * Quick solvability check - just determines if solvable, doesn't return solution
 * Slightly faster due to early termination optimization
 */
export function isSolvable(level: LevelConfig, maxTimeMs: number = 5000): boolean {
    const result = solvePuzzle(level, maxTimeMs);
    return result.solvable;
}
